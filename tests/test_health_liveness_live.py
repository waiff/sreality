def test_only_a_measured_problem_failing_for_two_cadences_without_an_incident_is_unalerted(cur):
    _beat(cur, "liveness-test-fresh", "0 minutes")
    for key in ("k_told", "k_acked", "k_stale", "k_unknown", "k_new", "k_cells", "k_bare"):
        _check(cur, key)
    _check(cur, "k_gauge", cls="gauge")
    _check(cur, "k_declared", declared="1 hour")
    failing = [{"subject": "s", "status": "fail"}]
    for key in ("k_told", "k_acked", "k_unknown", "k_gauge", "k_declared"):
        _result(cur, key, "fail", "3 hours", failing)
    _incident(cur, "cell:k_told:s")
    _incident(cur, "cell:k_acked:s", acknowledged=True)
    _result(cur, "k_stale", "fail", "20 hours", failing)
    _result(cur, "k_unknown", "unknown", "10 minutes")
    _result(cur, "k_new", "fail", "30 minutes", failing)
    # Since 633 a result without a verdict cell has no cell, as in the ladder: never the key's own.
    _result(cur, "k_bare", "fail", "3 hours")
    _result(cur, "k_bare", "fail", "10 minutes", [{"source": "bazos", "hidden": 7294}])
    _result(cur, "k_cells", "fail", "3 hours",
            [{"subject": "x", "status": "fail"}, {"subject": "y", "status": "ok"}])
    _result(cur, "k_cells", "fail", "10 minutes",
            [{"subject": "x", "status": "fail"}, {"subject": "y", "status": "fail"}, {"subject": "z", "status": "ok"}])

    [untold] = _liveness(cur)[3]["unalerted"]

    assert untold["facts"] == {"keys": ["k_cells"], "cells": ["k_cells:x"]}


def test_stale_is_judged_on_the_last_measured_result_never_on_unmeasured_rows(cur):
    """A key whose every run is Not measured (errored, timed out, skipped) goes stale from its last
    measurement, or from its declared_at when it never measured, so it is told by someone."""
    _beat(cur, "liveness-test-fresh", "0 minutes")
    _check(cur, "k_measured_then_unknown")
    _result(cur, "k_measured_then_unknown", "ok", "30 hours")
    _result(cur, "k_measured_then_unknown", "unknown", "1 hour")
    _check(cur, "k_never_measured")
    _result(cur, "k_never_measured", "unknown", "1 hour")
    _check(cur, "k_fresh")
    _result(cur, "k_fresh", "warn", "2 hours")
    _result(cur, "k_fresh", "unknown", "10 minutes")
    _check(cur, "k_young", declared="5 minutes")

    status, _value, _details, cells = _liveness(cur)

    assert status == "fail"
    assert {s for s in cells if s.startswith("stale:")} == {"stale:k_measured_then_unknown",
                                                            "stale:k_never_measured"}
    [measured] = cells["stale:k_measured_then_unknown"]
    assert measured["facts"]["last_measured_at"] is not None and 29.9 <= measured["value"] <= 30.1
    [never] = cells["stale:k_never_measured"]
    assert never["facts"]["last_measured_at"] is None and never["value"] >= 24 * 29


def _statement(start: str, end: str, migration: Path = _MIGRATION_629) -> str:
    """One statement of a migration (633 by default), exactly as the file runs it."""
    sql = migration.read_text(encoding="utf-8")
    head = sql.index(start)
    return sql[head:sql.index(end, head) + len(end)]


def _cron(cur: Any, *jobs: str) -> None:
    """The pg_cron stub holding these jobs, inside the test's transaction."""
    cur.execute("select to_regnamespace('cron') is not null")
    if cur.fetchone()[0]:
        pytest.fail("this database has a cron schema (pg_cron): the rail stubs one, so it runs against CI's "
                    "replay, which has none")
    cur.execute(_CRON_STUB)
    for job in jobs:
        cur.execute("insert into cron.job (jobname, schedule, command, active) values (%s, '*/5 * * * *', "
                    "'select 1', true)", (job,))


def test_migration_633_unschedules_the_capture_and_a_rerun_is_a_no_op(cur):
    """By job id looked up from its name: the capture goes, every other job stays, a second run finds nothing, and
    the post-condition then holds and keeps one liveness row."""
    _beat(cur, "liveness-test-fresh", "0 minutes")
    _cron(cur, "capture-data-quality", "health-liveness")
    unschedule = _statement("do $cron$", "$cron$;")

    cur.execute(unschedule)
    cur.execute(unschedule)

    cur.execute("select array_agg(jobname::text order by jobname) from cron.job")
    assert cur.fetchone()[0] == ["health-liveness"]
    cur.execute(_statement("do $post$", "$post$;"))
    cur.execute("select count(*) from pipeline_check_results where check_key = 'liveness'")
    assert cur.fetchone()[0] == 1


